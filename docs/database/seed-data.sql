/*
    E-BatterySwap - Demo seed data
    Target: SQL Server / E_BatterySwap
    Purpose: baseline data for Admin dashboard, station monitoring and battery inventory.

    IMPORTANT:
    - Run after docs/database/schema.sql.
    - Safe to run repeatedly: records are matched by unique business identifiers.
    - PasswordHash values are placeholders. Replace them with hashes generated by
      the Backend's configured password hasher before testing login.
    - All timestamps are generated in UTC.
*/

USE E_BatterySwap;
GO

SET XACT_ABORT ON;

BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @Now DATETIME2(3) = SYSUTCDATETIME();

    /* 1. Roles */
    IF NOT EXISTS (SELECT 1 FROM dbo.Role WHERE RoleCode = 'ADMIN')
        INSERT INTO dbo.Role (RoleCode, RoleName, Description, IsActive)
        VALUES ('ADMIN', N'Quản trị viên', N'Quản lý hệ thống và trạm đổi pin', 1);

    IF NOT EXISTS (SELECT 1 FROM dbo.Role WHERE RoleCode = 'CUSTOMER')
        INSERT INTO dbo.Role (RoleCode, RoleName, Description, IsActive)
        VALUES ('CUSTOMER', N'Khách hàng', N'Sử dụng dịch vụ đổi pin', 1);

    DECLARE @AdminRoleId BIGINT = (SELECT RoleId FROM dbo.Role WHERE RoleCode = 'ADMIN');
    DECLARE @CustomerRoleId BIGINT = (SELECT RoleId FROM dbo.Role WHERE RoleCode = 'CUSTOMER');

    /* 2. Demo accounts
       Replace PasswordHash before attempting to log in. */
    IF NOT EXISTS (SELECT 1 FROM dbo.Users WHERE Email = N'admin@ebatteryswap.local')
        INSERT INTO dbo.Users
            (RoleId, FullName, PhoneNumber, Email, PasswordHash, Status, CreatedAt)
        VALUES
            (@AdminRoleId, N'Quản trị hệ thống', '0900000001',
             N'admin@ebatteryswap.local', N'REPLACE_WITH_VALID_PASSWORD_HASH',
             'ACTIVE', @Now);

    IF NOT EXISTS (SELECT 1 FROM dbo.Users WHERE Email = N'customer@ebatteryswap.local')
        INSERT INTO dbo.Users
            (RoleId, FullName, PhoneNumber, Email, PasswordHash, Status, CreatedAt)
        VALUES
            (@CustomerRoleId, N'Khách hàng Demo', '0900000002',
             N'customer@ebatteryswap.local', N'REPLACE_WITH_VALID_PASSWORD_HASH',
             'ACTIVE', @Now);

    DECLARE @CustomerUserId BIGINT =
        (SELECT UserId FROM dbo.Users WHERE Email = N'customer@ebatteryswap.local');

    /* 3. Customer vehicle */
    IF NOT EXISTS (SELECT 1 FROM dbo.Vehicle WHERE LicensePlate = N'29A-12345')
        INSERT INTO dbo.Vehicle
            (UserId, LicensePlate, ModelName, BatteryCapacityCount, Status, CreatedAt)
        VALUES
            (@CustomerUserId, N'29A-12345', N'Electric Motorbike Demo', 2, 'ACTIVE', @Now);

    DECLARE @VehicleId BIGINT =
        (SELECT VehicleId FROM dbo.Vehicle WHERE LicensePlate = N'29A-12345');

    /* 4. Station */
    IF NOT EXISTS (SELECT 1 FROM dbo.Station WHERE StationCode = 'ST-HN-001')
        INSERT INTO dbo.Station
            (StationCode, StationName, Address, Latitude, Longitude, QRIdentifier,
             OperationalStatus, ConnectionStatus, LastSeenAt, CreatedAt)
        VALUES
            ('ST-HN-001', N'Trạm đổi pin Demo Cầu Giấy',
             N'Cầu Giấy, Hà Nội, Việt Nam', 21.036200, 105.790600,
             'QR-ST-HN-001', 'ACTIVE', 'ONLINE', @Now, @Now);

    DECLARE @StationId BIGINT =
        (SELECT StationId FROM dbo.Station WHERE StationCode = 'ST-HN-001');

    /* 5. Six station slots */
    INSERT INTO dbo.Slot
        (StationId, SlotNumber, DoorStatus, LockStatus, OperationalStatus, CreatedAt)
    SELECT @StationId, v.SlotNumber, 'CLOSED', 'LOCKED', 'AVAILABLE', @Now
    FROM (VALUES (1), (2), (3), (4), (5), (6)) AS v(SlotNumber)
    WHERE NOT EXISTS
    (
        SELECT 1
        FROM dbo.Slot s
        WHERE s.StationId = @StationId
          AND s.SlotNumber = v.SlotNumber
    );

    /* 6. Four batteries in slots and two batteries assigned to the demo vehicle */
    INSERT INTO dbo.Battery
        (SerialNumber, SOC, SOH, Temperature, CycleCount, OperationalStatus,
         LocationType, CurrentSlotId, LastTelemetryAt, CreatedAt)
    SELECT v.SerialNumber, v.SOC, v.SOH, v.Temperature, v.CycleCount,
           v.OperationalStatus, 'SLOT', s.SlotId, @Now, @Now
    FROM
    (
        VALUES
        (N'BAT-DEMO-001', 92.00, 99.00, 28.50, 12, 'NORMAL', 1),
        (N'BAT-DEMO-002', 78.00, 98.00, 29.00, 25, 'NORMAL', 2),
        (N'BAT-DEMO-003', 55.00, 97.00, 30.00, 41, 'NORMAL', 3),
        (N'BAT-DEMO-004', 31.00, 96.00, 31.50, 67, 'WARNING', 4)
    ) AS v(SerialNumber, SOC, SOH, Temperature, CycleCount, OperationalStatus, SlotNumber)
    INNER JOIN dbo.Slot s
        ON s.StationId = @StationId
       AND s.SlotNumber = v.SlotNumber
    WHERE NOT EXISTS
        (SELECT 1 FROM dbo.Battery b WHERE b.SerialNumber = v.SerialNumber);

    INSERT INTO dbo.Battery
        (SerialNumber, SOC, SOH, Temperature, CycleCount, OperationalStatus,
         LocationType, CurrentSlotId, LastTelemetryAt, CreatedAt)
    SELECT v.SerialNumber, v.SOC, v.SOH, v.Temperature, v.CycleCount,
           'NORMAL', 'VEHICLE', NULL, @Now, @Now
    FROM
    (
        VALUES
        (N'BAT-DEMO-005', 85.00, 99.00, 27.50, 8),
        (N'BAT-DEMO-006', 88.00, 99.00, 27.00, 9)
    ) AS v(SerialNumber, SOC, SOH, Temperature, CycleCount)
    WHERE NOT EXISTS
        (SELECT 1 FROM dbo.Battery b WHERE b.SerialNumber = v.SerialNumber);

    /* 7. Initial battery assignments to the demo vehicle */
    INSERT INTO dbo.BatteryAssignment
        (BatteryId, VehicleId, AssignedAt, EndedAt, AssignmentSource, RecordedByUserId)
    SELECT b.BatteryId, @VehicleId, @Now, NULL, 'INITIAL_HANDOVER',
           (SELECT UserId FROM dbo.Users WHERE Email = N'admin@ebatteryswap.local')
    FROM dbo.Battery b
    WHERE b.SerialNumber IN (N'BAT-DEMO-005', N'BAT-DEMO-006')
      AND NOT EXISTS
      (
          SELECT 1
          FROM dbo.BatteryAssignment ba
          WHERE ba.BatteryId = b.BatteryId
            AND ba.EndedAt IS NULL
      );

    /* 8. Initial telemetry history */
    INSERT INTO dbo.BatteryTelemetry
        (BatteryId, SOC, SOH, Temperature, MeasuredAt, ReceivedAt, Source)
    SELECT b.BatteryId, b.SOC, b.SOH, b.Temperature, @Now, @Now, 'SIMULATOR'
    FROM dbo.Battery b
    WHERE b.SerialNumber LIKE N'BAT-DEMO-%'
      AND NOT EXISTS
      (
          SELECT 1
          FROM dbo.BatteryTelemetry bt
          WHERE bt.BatteryId = b.BatteryId
            AND bt.Source = 'SIMULATOR'
      );

    COMMIT TRANSACTION;

    /* Summary: expected baseline counts are 2 roles, 2 users, 1 vehicle,
       1 station, 6 slots, 6 batteries, 2 active assignments, 6 telemetry rows. */
    SELECT 'Role' AS Entity, COUNT(*) AS Total
    FROM dbo.Role WHERE RoleCode IN ('ADMIN', 'CUSTOMER')
    UNION ALL SELECT 'Users', COUNT(*) FROM dbo.Users
        WHERE Email IN (N'admin@ebatteryswap.local', N'customer@ebatteryswap.local')
    UNION ALL SELECT 'Vehicle', COUNT(*) FROM dbo.Vehicle WHERE LicensePlate = N'29A-12345'
    UNION ALL SELECT 'Station', COUNT(*) FROM dbo.Station WHERE StationCode = 'ST-HN-001'
    UNION ALL SELECT 'Slot', COUNT(*) FROM dbo.Slot WHERE StationId = @StationId
    UNION ALL SELECT 'Battery', COUNT(*) FROM dbo.Battery WHERE SerialNumber LIKE N'BAT-DEMO-%'
    UNION ALL SELECT 'ActiveAssignments', COUNT(*) FROM dbo.BatteryAssignment
        WHERE VehicleId = @VehicleId AND EndedAt IS NULL
    UNION ALL SELECT 'Telemetry', COUNT(*) FROM dbo.BatteryTelemetry bt
        INNER JOIN dbo.Battery b ON b.BatteryId = bt.BatteryId
        WHERE b.SerialNumber LIKE N'BAT-DEMO-%';

END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0
        ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO
